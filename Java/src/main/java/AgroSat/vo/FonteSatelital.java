package AgroSat.vo;

public class FonteSatelital {

    private Long idFonte;
    private String nmFonte;
    private String dsUrl;
    private String dsTipoDado;
    private String dsDescricao;
    private String dtCadastro;

    public Long getIdFonte() {
        return idFonte;
    }

    public void setIdFonte(Long idFonte) {
        this.idFonte = idFonte;
    }

    public String getNmFonte() {
        return nmFonte;
    }

    public void setNmFonte(String nmFonte) {
        this.nmFonte = nmFonte;
    }

    public String getDsUrl() {
        return dsUrl;
    }

    public void setDsUrl(String dsUrl) {
        this.dsUrl = dsUrl;
    }

    public String getDsTipoDado() {
        return dsTipoDado;
    }

    public void setDsTipoDado(String dsTipoDado) {
        this.dsTipoDado = dsTipoDado;
    }

    public String getDsDescricao() {
        return dsDescricao;
    }

    public void setDsDescricao(String dsDescricao) {
        this.dsDescricao = dsDescricao;
    }

    public String getDtCadastro() {
        return dtCadastro;
    }

    public void setDtCadastro(String dtCadastro) {
        this.dtCadastro = dtCadastro;
    }

}